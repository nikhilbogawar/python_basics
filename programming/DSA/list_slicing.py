#  -6 -5 -4 -3 -2 -1
l=[10,20,30,40,50,60]
#   0  1  2  3  4  5
print(l[1:4:1]) # [20, 30, 40]
print(l[1:4]) # [20, 30, 40]
print(l[2:]) # [30, 40, 50, 60]
print(l[:4]) # [10, 20, 30, 40]

print(l[0:len(l):2]) # [10, 30, 50]
print(l[0:len(l)]) # [10, 20, 30, 40, 50, 60]
print(l[0::]) # [10, 20, 30, 40, 50, 60]
print(l[::]) # [10, 20, 30, 40, 50, 60]
print(l[:]) # [10, 20, 30, 40, 50, 60]

print(l[2:6:-1]) # []
print(l[5:2:-1]) # [60, 50, 40]

print(l[5:0:-2]) # [60, 40, 20]
print(l[4:2:-1]) # [50, 40]
print(l[2:4:-1]) # []
print(l[4:2:1]) # []

print(l[-5:4:1]) # [20, 30, 40]
print(l[-6:-2:1]) # [10, 20, 30, 40]
print(l[-4:0:-1]) # [30, 20]

print(l[4:0:-1]) # [50, 40, 30, 20]
print(l[4:-7:-1]) # [50, 40, 30, 20, 10]
print(l[4::-1]) # [50, 40, 30, 20, 10]

print(l[:-7:-1]) # [60, 50, 40, 30, 20, 10]
print(l[::-1]) # [60, 50, 40, 30, 20, 10]
print(l[5::-1]) # [60, 50, 40, 30, 20, 10]